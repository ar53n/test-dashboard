import type { OrgNode } from '../../../shared/contract.ts'

/**
 * Системный промпт. Названия дивизионов и отделов подсказывают модели, к чему относятся
 * слова вроде «в Продажах»; сами данные и метрики модели не передаются.
 */
export function buildSystemPrompt(nodes: readonly OrgNode[]): string {
  const byId = new Map(nodes.map((node) => [node.id, node]))
  const divisions = nodes.filter((node) => node.parentId === null).map((node) => node.name)
  const departments = nodes
    .filter((node) => node.parentId !== null && byId.get(node.parentId)?.parentId === null)
    .map((node) => node.name)

  return [
    'Ты переводишь запрос пользователя об оргструктуре компании в JSON-фильтр по заданной схеме. Отвечай только JSON.',
    '',
    'Иерархия: дивизион (level 1) → отдел (level 2) → команда (level 3).',
    'Показатели подразделения:',
    '- headcount — сотрудники самого подразделения; budget — его собственный бюджет в рублях; performance — его эффективность 0–100.',
    '- totalHeadcount и totalBudget — подразделение вместе со всеми вложенными; avgPerformance — средняя эффективность поддерева, взвешенная по численности, 0–100.',
    'Если пользователь говорит «сотрудников», «бюджет», «эффективность» без слов «собственный» или «сам», используй totalHeadcount, totalBudget, avgPerformance.',
    '',
    'Правила:',
    '- Числа — абсолютные значения: «1,5 млн» = 1500000, «200 тысяч» = 200000.',
    '- «больше/выше» → gt, «не меньше/от» → gte, «меньше/ниже» → lt, «не больше/до» → lte.',
    '- nameContains — подстрока названия самого подразделения; ancestorName — подстрока названия вышестоящего подразделения («команды в Продажах» → levels [3], ancestorName «Продаж»).',
    '- Для текстовых полей используй основу слова без окончания, чтобы подстрока совпала с любой формой.',
    '- «топ-5», «первые 5», «5 самых» → limit 5 и sort по соответствующему показателю (desc для «самых больших/лучших»).',
    '- Условия, которых нет в запросе, — null. Не придумывай условий. Если запрос не про оргструктуру, все поля null.',
    '',
    `Дивизионы: ${divisions.join(', ') || '—'}.`,
    `Отделы: ${departments.join(', ') || '—'}.`,
  ].join('\n')
}
